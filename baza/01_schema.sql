-- =====================================================================================================
-- 01_schema.sql - schemat bazy perfum (PostgreSQL 15+ z rozszerzeniem pgvector 0.5+)
-- Uruchom na pustej bazie:  psql -U <uzytkownik> -d <baza> -f baza/01_schema.sql
-- Kolejnosc: rozszerzenia -> typy wyliczeniowe -> tabele (najpierw slowniki, potem tabele zalezne).
-- Indeksy nietrywialne (wektorowy, trigramowe) powstaja w 03_indexes_and_checks.sql PO zaladowaniu danych.
-- =====================================================================================================
\set ON_ERROR_STOP on

CREATE EXTENSION IF NOT EXISTS vector;      -- typ vector(n) i operatory odleglosci (pgvector)
CREATE EXTENSION IF NOT EXISTS pg_trgm;     -- wyszukiwanie po nazwach (podobienstwo trigramowe)

CREATE TYPE gender_t        AS ENUM ('women', 'men', 'unisex');
CREATE TYPE layer_t         AS ENUM ('top', 'middle', 'base');            -- warstwa piramidy zapachowej
CREATE TYPE cluster_level_t AS ENUM ('family', 'subfamily');              -- rodzina (7) lub podrodzina (17)

-- ---------- slowniki ----------
CREATE TABLE countries (
    country_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text    NOT NULL UNIQUE
);

CREATE TABLE brands (
    brand_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text    NOT NULL UNIQUE,
    country_id  integer NOT NULL REFERENCES countries (country_id)
);

CREATE TABLE perfumers (                                                    -- perfumiarze (oraz domy zapachowe: is_company)
    perfumer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text    NOT NULL UNIQUE,
    is_company  boolean NOT NULL DEFAULT false
);

CREATE TABLE accords (
    accord_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text    NOT NULL UNIQUE
);

CREATE TABLE general_notes (                                                -- nuty ogolne (uzupelniane po weryfikacji slownika nut)
    general_note_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text    NOT NULL UNIQUE
);

CREATE TABLE notes (                                                        -- nuty szczegolowe
    note_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text    NOT NULL UNIQUE,
    general_note_id integer REFERENCES general_notes (general_note_id)      -- NULL do czasu uzupelnienia hierarchii
);

-- ---------- klastry zapachowe: 7 rodzin (bez rodzica) i 17 podrodzin (z rodzicem) ----------
CREATE TABLE clusters (
    cluster_id        integer PRIMARY KEY,                                  -- id nadane w klasteryzacji (1-17 podrodziny, 101-107 rodziny)
    level             cluster_level_t NOT NULL,
    parent_cluster_id integer REFERENCES clusters (cluster_id),
    name              text NOT NULL,
    description       text,
    centroid          vector(512) NOT NULL,                                 -- srodek klastra (dlugosc 1): do przypisania nowej perfumy i centrow uzytkownika
    CONSTRAINT clusters_level_parent_ck CHECK ((level = 'family' AND parent_cluster_id IS NULL) OR (level = 'subfamily' AND parent_cluster_id IS NOT NULL))
);

-- ---------- perfumy ----------
CREATE TABLE perfumes (
    perfume_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fragrantica_id      integer UNIQUE,                                     -- id ze zrodla; NULL dla perfum dodanych recznie
    url                 text NOT NULL UNIQUE,
    name                text NOT NULL,                                      -- BEZ ograniczenia unikalnosci: ta sama marka i nazwa moga wystapic dwa razy (osobne wpisy zrodla)
    brand_id            integer NOT NULL REFERENCES brands (brand_id),
    gender              gender_t NOT NULL,
    release_year        smallint CHECK (release_year BETWEEN 1500 AND 2100),
    source_rating_value numeric(3, 2) CHECK (source_rating_value BETWEEN 0 AND 5),
    source_rating_count integer CHECK (source_rating_count >= 0),
    cluster_id          integer NOT NULL REFERENCES clusters (cluster_id),  -- podrodzina; rodzina = clusters.parent_cluster_id
    cluster_distance    real    NOT NULL CHECK (cluster_distance >= 0),     -- 1 - cosinus do srodka podrodziny
    created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE perfume_embeddings (                                           -- relacja 1:1 z perfumes (wektor trzymany osobno, zeby tabela perfumes zostala lekka)
    perfume_id integer PRIMARY KEY REFERENCES perfumes (perfume_id) ON DELETE CASCADE,
    embedding  vector(512) NOT NULL                                         -- wektor jednostkowy; odleglosc cosinusowa: operator <=>
);

CREATE TABLE perfume_perfumers (
    perfume_id  integer NOT NULL REFERENCES perfumes (perfume_id)   ON DELETE CASCADE,
    perfumer_id integer NOT NULL REFERENCES perfumers (perfumer_id),
    PRIMARY KEY (perfume_id, perfumer_id)
);

CREATE TABLE perfume_notes (
    perfume_id integer NOT NULL REFERENCES perfumes (perfume_id) ON DELETE CASCADE,
    note_id    integer NOT NULL REFERENCES notes (note_id),
    layer      layer_t NOT NULL,
    PRIMARY KEY (perfume_id, note_id, layer)                                -- ta sama nuta moze byc w kilku warstwach jednej perfumy
);

CREATE TABLE perfume_accords (
    perfume_id  integer  NOT NULL REFERENCES perfumes (perfume_id) ON DELETE CASCADE,
    accord_id   integer  NOT NULL REFERENCES accords (accord_id),
    accord_rank smallint NOT NULL CHECK (accord_rank BETWEEN 1 AND 5),     -- 1 = najbardziej wyczuwalny
    PRIMARY KEY (perfume_id, accord_id),
    UNIQUE (perfume_id, accord_rank)
);

COMMENT ON TABLE  clusters                 IS 'Klastry zapachowe z clustering.ipynb: 7 rodzin (level=family) i 17 podrodzin (level=subfamily)';
COMMENT ON COLUMN perfumes.cluster_id      IS 'Podrodzina perfumy = najblizszy srodek (cosinus); rodzina przez clusters.parent_cluster_id';
COMMENT ON COLUMN perfumes.cluster_distance IS '1 - cosinus miedzy wektorem perfumy a srodkiem jej podrodziny';
COMMENT ON COLUMN notes.general_note_id    IS 'NULL do czasu zakonczenia weryfikacji slownika nut ogolnych';
